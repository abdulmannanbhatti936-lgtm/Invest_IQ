def css_for(key: str) -> str:
    d = DIRECTIONS[key]
    t = d[d["primary_mode"]]
    out = [
        f"/* {d['name']} ({d['primary_mode']}) preview, generated by tools/preview_css.py */",
        ":root {",
    ]
    out += [f"  --t-{k}: {v};" for k, v in t.items()]
    out += [f"  --color-{tw}: var(--t-{tok});" for tw, tok in TAILWIND.items()]
    out.append("}")
    for hex_, tok in CHART.items():
        out.append(f"[stroke='{hex_}'] {{ stroke: var(--t-{tok}); }}")
        out.append(f"[fill='{hex_}'] {{ fill: var(--t-{tok}); }}")
    out.append(COMMON)
    out.append(CHARACTER[key])
    return "\n".join(out)


if __name__ == "__main__":
    for key in DIRECTIONS:
        folder = HERE / key
        folder.mkdir(exist_ok=True)
        (folder / "preview.css").write_text(css_for(key) + "\n", encoding="utf-8")
        print("wrote", folder / "preview.css")
